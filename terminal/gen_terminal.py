GHOSTTY_SET = {
    "font-family": "Space Mono", "font-size": "11", "adjust-cell-height": "12%",
    "background-opacity": "1.00", "bold-is-bright": "false",
    "cursor-style": "block", "cursor-style-blink": "false",
    "shell-integration-features": "no-cursor,sudo",
    "window-padding-x": "16", "window-padding-y": "14", "window-padding-balance": "true",
    "theme": "nothing",
}
GHOSTTY_DROP = {"selection-background", "selection-foreground", "background-blur-radius"}


def ghostty_config(original):
    seen, out = set(), []
    for line in original.splitlines():
        k = line.split("=", 1)[0].strip() if "=" in line and not line.lstrip().startswith("#") else None
        if k in GHOSTTY_DROP:
            continue
        if k in GHOSTTY_SET:
            out.append(f"{k} = {GHOSTTY_SET[k]}"); seen.add(k)
        else:
            out.append(line)
    add = [f"{k} = {v}" for k, v in GHOSTTY_SET.items() if k not in seen]
    if add:
        out += ["", "# Nothing"] + add
    return "\n".join(out) + "\n"


