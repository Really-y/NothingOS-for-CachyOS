def logo_text():
    """Original mark: a 9x9 dot ring (white) on a dot grid, one red dot at the centre."""
    import math
    rows = []
    for y in range(9):
        cells = []
        for x in range(9):
            d = math.hypot(x - 4, y - 4)
            if x == 4 and y == 4: cells.append("$3●")
            elif 3.0 <= d <= 4.3 and not (x > 4 and y == 4): cells.append("$1●")
            else: cells.append("$2·")
        rows.append(" ".join(cells))
    return "\n".join(rows) + "\n"


