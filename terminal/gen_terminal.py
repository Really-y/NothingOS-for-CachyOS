#!/usr/bin/env python3
"""Nothing design for terminals, generated from palette.json.

  gen_terminal.py            generate into terminal/out/
  gen_terminal.py --install  generate, back up originals to
                             ~/.local/share/nothingos-backup/terminal/, deploy
  gen_terminal.py --restore  put the backups back (removes files we created)

Terminals: Konsole, Alacritty, Ghostty, Kitty, WezTerm, + Starship, fastfetch.
Only appearance is touched; keybindings / shell / scrollback stay as they are.
"""
import json, os, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
HOME = Path.home()
CFG = HOME / ".config"
SHARE = HOME / ".local/share"
BACKUP = SHARE / "nothingos-backup/terminal"

P = json.load(open(HERE / "palette.json"))
NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
ANSI = [P["normal"][n] for n in NAMES] + [P["bright"][n] for n in NAMES]


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def tc(h, bg=False):
    r, g, b = rgb(h)
    return f"\x1b[{48 if bg else 38};2;{r};{g};{b}m"


def w(rel, text):
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)


