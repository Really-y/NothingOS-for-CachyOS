#!/usr/bin/env python3
"""sultry.svg = the glam head (scaled 0.72, tilted 8 deg chin-down) + an elegant off-shoulder dress."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
S = 'translate(84,11.2) scale(0.72) '
s = open(os.path.join(HERE, "glam.svg")).read()
s = s.replace('<!-- "Glam" style', '<!-- "Sultry" style (generated by make_sultry.py from glam.svg)\n     ', 1)
s = s.replace('transform="rotate(-5 300 480)"', 'transform="%srotate(-8 300 480)"' % S)
s = s.replace('<g id="neck">', '<g id="neck" transform="%s">' % S.strip())
i = s.index('  <g id="body"'); j = s.index('</g>', i) + 4
s = s[:i] + open(os.path.join(HERE, "sultry-body.svgfrag")).read().rstrip() + s[j:]
s = s.replace('    <filter id="soft"', '''    <linearGradient id="skinBody" x1="94" y1="0" x2="506" y2="0" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#b0b0b0"/><stop offset="0.45" stop-color="#cfcfcf"/><stop offset="1" stop-color="#8c8c8c"/>
    </linearGradient>
    <filter id="soft"''', 1)
open(os.path.join(HERE, "sultry.svg"), "w").write(s)
print("ok sultry.svg")
