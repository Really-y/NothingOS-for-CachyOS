#!/usr/bin/env python3
"""sultry.svg = sultry-body.svgfrag wrapped in the svg header (one self-contained drawing).

Three-quarter BACK view in a backless evening gown, looking back over her near (viewer-left)
shoulder. The head is drawn in its own local frame (three-quarter profile facing viewer-left,
far eye foreshortened behind the nose bridge) and placed with HEAD below; the body is in canvas
coordinates. Group ids match gen_figure.GROUPS (face/eyes/neck -> face mask, eyes-open/closed ->
blink, hair-back/hair-curtain -> sway). Non-explicit by design: the gown covers the sides and the
small of the back, straps on both shoulders, hair over the far armpit.

The red earring bead is drawn by the shader at BEAD (canvas) -> GlyphField.clipUV.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = (294, 294, -8, 1.35)       # translate x, y, rotate deg, scale  (local head frame -> canvas)
BEAD_LOCAL = (44, 35)
FRAME = (24, 0, 0.92)       # whole drawing: translate x, y, scale (keeps the hip flare in frame)


def head_to_canvas(p):
    tx, ty, r, k = HEAD
    a = math.radians(r)
    x, y = p[0] * k, p[1] * k
    cx, cy = tx + x * math.cos(a) - y * math.sin(a), ty + x * math.sin(a) + y * math.cos(a)
    return (FRAME[0] + FRAME[2] * cx, FRAME[1] + FRAME[2] * cy)


frag = open(os.path.join(HERE, "sultry-body.svgfrag")).read().rstrip()
frag = frag.replace("{HEAD}", "translate(%g,%g) rotate(%g) scale(%g)" % HEAD)
s = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- "Sultry" style for org.nothing.dots (generated by make_sultry.py from sultry-body.svgfrag):
     an original ADULT woman, three-quarter back view in a backless gown, glancing back over her
     shoulder. Non-explicit. Values are LUMINANCE MAPS (grey = dot size/brightness); in the face
     dark features become missing dots; 1.0 highlights are forced to full-size dots. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"
     width="600" height="800" viewBox="0 0 600 800">
  <defs>
    <filter id="soft" x="-30%" y="-60%" width="160%" height="220%"><feGaussianBlur stdDeviation="7"/></filter>
    <filter id="soft2" x="-30%" y="-60%" width="160%" height="220%"><feGaussianBlur stdDeviation="3"/></filter>
  </defs>
''' + '  <g transform="translate(%g,%g) scale(%g)">\n' % FRAME + frag + "\n  </g>\n</svg>\n"
open(os.path.join(HERE, "sultry.svg"), "w").write(s)
bx, by = head_to_canvas(BEAD_LOCAL)
print("ok sultry.svg  bead canvas (%.2f, %.2f)" % (bx, by))
