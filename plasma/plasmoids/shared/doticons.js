// WMO weather code (Open-Meteo) → pictogram; falls back to Material icon names.
function forWeather(code, icon) {
    if (code !== undefined && code !== null && !isNaN(code)) {
        if (code <= 1) return "sun";
        if (code === 2) return "partly";
        if (code === 3) return "cloud";
        if (code === 45 || code === 48) return "fog";
        if (code >= 71 && code <= 77) return "snow";
        if (code === 85 || code === 86) return "snow";
        if (code >= 95) return "storm";
        if (code >= 51) return "rain";
    }
    var m = { clear_day: "sun", sunny: "sun", partly_cloudy_day: "partly", cloud: "cloud",
              foggy: "fog", rainy: "rain", weather_snowy: "snow", thunderstorm: "storm" };
    return m[icon] || "cloud";
}
